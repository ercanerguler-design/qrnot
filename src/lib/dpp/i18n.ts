export const DICTS: Record<DppLang, Dict> = { tr, en, de, fr, es, nl, ar, ru }

export const LOCALES: Record<DppLang, string> = { tr: 'tr-TR', en: 'en-GB', de: 'de-DE', fr: 'fr-FR', es: 'es-ES', nl: 'nl-NL', ar: 'ar', ru: 'ru-RU' }

export type MsgParams = Record<string, string | number>

export function msg(lang: DppLang, key: MsgKey, params: MsgParams = {}) {
  const template = DICTS[lang]?.[key] ?? tr[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] !== undefined ? String(params[k]) : `{${k}}`))
}

/** Sunucunun fırlattığı, dile çevrilebilen hata. Mesajı varsayılan olarak Türkçedir; API katmanı istenen dile çevirir. */
export class DppError extends Error {
  constructor(
    public key: MsgKey,
    public params: MsgParams = {},
    /** Yayın eksikleri gibi liste parametreleri (her biri ayrı çevrilir) */
    public list: Array<{ key: MsgKey; params?: MsgParams }> = []
  ) {
    super(msg('tr', key, params))
  }
}

/** DppError'ı istenen dilde metne çevirir; diğer hatalar için genel mesaj. */
export function errorText(err: unknown, lang: DppLang) {
  if (err instanceof DppError) {
    const list = err.list.map((i) => msg(lang, i.key, i.params)).join(', ')
    return msg(lang, err.key, { ...err.params, ...(err.list.length ? { list } : {}) })
  }
  return msg(lang, 'e_server')
}
